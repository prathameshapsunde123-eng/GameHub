var age =25;
var age =40;  // var : Variable can be re-declared & updated. A global scope variable.
console.log(age);


let price =100;
price = 101;        // let : Variable cannot be re-declared but can be updated. A block scope variable.
console.log(price);



const name = "don";  // const : Variable cannot be re-declared or updated. A block scope variable.
console.log(name);